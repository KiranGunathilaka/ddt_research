#!/usr/bin/env python3
"""Link every HTML doc from index.html and build the public copy for GitHub Pages.

  * every .html file in the repository root except index.html is a doc; its <head>
    needs <title>, <meta name="description">, <meta name="doc-section"> (one of
    SECTIONS) and <meta name="date" content="YYYY-MM-DD">
  * index.html is regenerated as the hub, and every doc gets the same docs bar
    right after <body>
  * --site DIR writes the public copy: the docs, the figures they show and
    DOWNLOADS only. Links into submodules go to upstream at the pinned commit,
    links to papers go to their public source, anything else to the private repo
  * --publish writes the public copy to PAGES_BRANCH of PAGES_REMOTE and pushes it

Run from the repository root after adding or changing a doc:  python3 tools/build_docs.py
"""
import argparse
import collections
import datetime
import html
import json
import os
import re
import shutil
import subprocess
import tempfile
from urllib.parse import quote, unquote

SECTIONS = {
    "Plan": "What we are building and how we will test it.",
    "Findings": "The research behind the plan.",
    "Tools": "Interactive references.",
    "Reference": "Everything collected, with its sources.",
}
DOWNLOADS = [
    ("xlsx/ddt_essential_costs.xlsx", "Cost workbook", "essential parts with landed cost in LKR, power budget, Jetson vs PC"),
    ("ddt_architecture_and_testing.pdf", "Architecture and test plan (PDF)", "printable copy of the plan"),
]
REPO = "https://github.com/KiranGunathilaka/ddt_research"
PAGES_REMOTE = "git@github.com:KiranGunathilaka/ddt_research.git"
# Pages serves this branch: it holds only the public copy, so the Pages build never
# meets the submodules on main (one has a nested submodule with no URL)
PAGES_BRANCH = "gh-pages"
BEGIN = "<!-- docs-bar: generated by tools/build_docs.py -->"
END = "<!-- /docs-bar -->"
LFS_POINTER = b"version https://git-lfs.github.com/spec/v1"
ATTR = re.compile(r'\b(href|src)="([^"]*)"')
EXTERNAL = re.compile(r"^([a-z][a-z0-9+.-]*:|#|//|$)", re.I)

