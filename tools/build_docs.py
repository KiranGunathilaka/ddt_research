def git(*args, cwd=None):
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def head_meta(text):
    found = {}
    for tag in re.findall(r"<meta\b[^>]*>", text):
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', tag))
        if "name" in attrs and "content" in attrs:
            found[attrs["name"]] = html.unescape(attrs["content"])
    title = re.search(r"<title>(.*?)</title>", text, re.S)
    found["title"] = html.unescape(title.group(1).strip()) if title else ""
    return found


def load_docs():
    docs, problems = [], []
    for name in sorted(os.listdir(".")):
        if not name.endswith(".html") or name == "index.html":
            continue
        meta = head_meta(read(name))
        missing = [k for k in ("title", "description", "doc-section", "date") if not meta.get(k)]
        if meta.get("doc-section") and meta["doc-section"] not in SECTIONS:
            missing.append("doc-section from " + ", ".join(SECTIONS))
        if missing:
            problems.append(f"{name}: add {'; '.join(missing)}")
        else:
            docs.append(dict(meta, file=name))
    if problems:
        raise SystemExit("Docs missing <head> tags:\n  " + "\n  ".join(problems))
    docs.sort(key=lambda d: d["date"], reverse=True)
    return sorted(docs, key=lambda d: list(SECTIONS).index(d["doc-section"]))


def bar(docs, current):
    def link(href, label, cls=""):
        here = ' aria-current="page"' if href == current else ""
        return f'<a{cls} href="{href}"{here}>{html.escape(label)}</a>'
    home = link("index.html", "Falcon DDT docs", ' class="docs-home"')
    links = "".join(link(d["file"], d["title"]) for d in docs)
    return (f'{BEGIN}\n<div class="docs-bar" role="navigation" aria-label="Falcon DDT docs"><style>{BAR_CSS}</style>'
            f'{home}<span class="docs-links">{links}</span></div>\n{END}')


def with_bar(text, block):
    if BEGIN in text:
        start, stop = text.index(BEGIN), text.index(END) + len(END)
        return text[:start] + block + text[stop:]
    body = re.search(r"<body\b[^>]*>", text)
    if not body:
        raise SystemExit("no <body> tag to put the docs bar after")
    return text[:body.end()] + "\n" + block + "\n" + text[body.end():]


def hub(docs):
    sections = []
    for name, blurb in SECTIONS.items():
        cards = []
        for d in (d for d in docs if d["doc-section"] == name):
            day = datetime.date.fromisoformat(d["date"])
            date = f"{day.day} {day:%b %Y}"
            cards.append(f'<a class="card" href="{d["file"]}"><b>{html.escape(d["title"])}</b>'
                         f'<span>{html.escape(d["description"])}</span><span class="m">{date}</span></a>')
        if cards:
            sections.append(f'<h2>{name}</h2>\n<p class="m">{blurb}</p>\n<div class="cards">\n' + "\n".join(cards) + "\n</div>")
    downloads = [f'<li><a href="{path}">{html.escape(label)}</a> <span class="m">{html.escape(note)}</span></li>'
                 for path, label, note in DOWNLOADS if os.path.exists(path)]
    return (HUB.replace("%BAR%", bar(docs, "index.html")).replace("%SECTIONS%", "\n".join(sections))
            .replace("%DOWNLOADS%", "\n".join(downloads)).replace("%REPO%", REPO))


def update_repo(docs):
    for d in docs:
        text = read(d["file"])
        updated = with_bar(text, bar(docs, d["file"]))
        if updated != text:
            write(d["file"], updated)
    write("index.html", hub(docs))


def submodules():
    names = {}
    for line in git("config", "-f", ".gitmodules", "--get-regexp", r"^submodule\..*\.(path|url)$").splitlines():
        key, value = line.split(" ", 1)
        name, field = key[len("submodule."):].rsplit(".", 1)
        names.setdefault(name, {})[field] = value
    urls = {v["path"]: v["url"] for v in names.values()}
    pinned = {}
    for line in git("ls-tree", "-r", "HEAD").splitlines():
        info, path = line.split("\t", 1)
        mode, _, sha = info.split()
        if mode == "160000" and path in urls:
            url = re.sub(r"\.git$", "", urls[path])
            url = re.sub(r"^git@([^:]+):", r"https://\1/", url)
            pinned[path] = (url + ("/-" if "gitlab" in url else ""), sha)
    return pinned


def online(path, pinned, papers):
    """Where a local repository path lives online, as (kind, url)."""
    for root, (base, sha) in pinned.items():
        if path == root or path.startswith(root + "/"):
            inner = path[len(root) + 1:]
            is_dir = os.path.isdir(path) if os.path.exists(path) else "." not in os.path.basename(inner)
            kind = "tree" if not inner or is_dir else "blob"
            return "upstream code", f"{base}/{kind}/{sha}" + (f"/{quote(inner)}" if inner else "")
    if path in papers:
        return "paper", papers[path]
    if os.path.lexists(path):
        return "private repo", f"{REPO}/{'tree' if os.path.isdir(path) else 'blob'}/main/{quote(path)}"
    return None, None


def build_site(dest, docs):
    for name in os.listdir(dest):
        target = os.path.join(dest, name)
        if name != ".git":
            shutil.rmtree(target) if os.path.isdir(target) and not os.path.islink(target) else os.remove(target)
    pinned = submodules()
    papers = {p["file"]: p["url"] for p in json.load(open("sources.json", encoding="utf-8"))["papers"]}
    pages = ["index.html"] + [d["file"] for d in docs]
    published = {"sources.json"} | {p for p, _, _ in DOWNLOADS}
    counts, unresolved, skipped = collections.Counter(), set(), set()

    def copy(path):
        with open(path, "rb") as f:
            if f.read(len(LFS_POINTER)) == LFS_POINTER:
                skipped.add(path)
                return
        os.makedirs(os.path.join(dest, os.path.dirname(path)), exist_ok=True)
        shutil.copy2(path, os.path.join(dest, path))

    def fix(match):
        attr, value = match.groups()
        if "${" in value or EXTERNAL.match(value):
            return match.group(0)
        target, hashmark, fragment = value.partition("#")
        path = os.path.normpath(unquote(html.unescape(target.partition("?")[0])))
        if path in pages:
            return match.group(0)
        if path in published or path.startswith("figures/"):
            if os.path.isfile(path):
                copy(path)
            return match.group(0)
        kind, url = online(path, pinned, papers)
        if not url:
            unresolved.add(path)
            return match.group(0)
        counts[kind] += 1
        keep_fragment = hashmark and (kind != "paper" or url.lower().endswith(".pdf"))
        return f'{attr}="{html.escape(url)}{"#" + fragment if keep_fragment else ""}"'

    for page in pages:
        write(os.path.join(dest, page), ATTR.sub(fix, read(page)))
    copy("sources.json")
    open(os.path.join(dest, ".nojekyll"), "w").close()
    print(f"public copy in {dest}: " + ", ".join(f"{n} links to {k}" for k, n in sorted(counts.items())))
    for path in sorted(skipped):
        print(f"  not copied, LFS file not downloaded: {path}")
    for path in sorted(unresolved):
        print(f"  left as is, no such path: {path}")


def publish(docs):
    commit = git("rev-parse", "--short", "HEAD").strip()
    dirty = git("status", "--porcelain", "--", "*.html", "figures", "xlsx").strip()
    with tempfile.TemporaryDirectory() as clone:
        if git("ls-remote", "--heads", PAGES_REMOTE, PAGES_BRANCH).strip():
            git("clone", "--depth", "1", "--branch", PAGES_BRANCH, PAGES_REMOTE, clone)
        else:
            git("init", "-q", "-b", PAGES_BRANCH, clone)
            git("remote", "add", "origin", PAGES_REMOTE, cwd=clone)
        build_site(clone, docs)
        git("add", "-A", cwd=clone)
        if not git("status", "--porcelain", cwd=clone).strip():
            print("public copy unchanged, nothing pushed")
            return
        note = " with local changes" if dirty else ""
        git("commit", "-q", "-m", f"Publish docs from ddt_research {commit}{note}.", cwd=clone)
        git("push", "-q", "origin", f"HEAD:{PAGES_BRANCH}", cwd=clone)
        print(f"pushed to {PAGES_BRANCH} of {PAGES_REMOTE}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--site", metavar="DIR", help="also write the public copy into DIR")
    parser.add_argument("--publish", action="store_true", help=f"also push the public copy to {PAGES_BRANCH} of {PAGES_REMOTE}")
    args = parser.parse_args()
    docs = load_docs()
    update_repo(docs)
    print(f"{len(docs)} docs linked from index.html")
    if args.site:
        os.makedirs(args.site, exist_ok=True)
        build_site(args.site, docs)
    if args.publish:
        publish(docs)


if __name__ == "__main__":
    main()
