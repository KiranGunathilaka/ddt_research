#!/usr/bin/env python3
"""Keep .gitattributes and .gitignore in step with the archive.

  * every file of 1 MiB or more is stored in Git LFS
  * LFS pointer files that third-party repos committed, and whose content was
    never downloaded, are ignored: committing them makes pushes and clones fail
    on the missing objects

Additive: existing entries are kept while their file still exists.
Run from the repository root after adding material:  python3 tools/lfs_attributes.py
"""
import os
import subprocess

THRESHOLD = 1 << 20
# Types that are always heavy; tracked by pattern so new ones need no regeneration.
PATTERNS = ["pdf", "pt", "pth", "weights", "onnx", "mp4", "avi", "bag", "db3", "mcap", "zip"]
LFS = "filter=lfs diff=lfs merge=lfs -text"
POINTER = b"version https://git-lfs.github.com/spec/v1"
BEGIN = "# >>> upstream LFS placeholders (generated by tools/lfs_attributes.py)"
END = "# <<< upstream LFS placeholders"
SPACE = "[[:space:]]"


def escape(path, space=SPACE):
    out = []
    for ch in path:
        if ch == " ":
            out.append(space)
        elif ch in '\\*?[]"':
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "/" + "".join(out)


def unescape(pattern):
    out, chars = [], iter(pattern[1:].replace(SPACE, " "))
    for ch in chars:
        out.append(next(chars, "") if ch == "\\" else ch)
    return "".join(out)


def git_files(*args):
    listed = subprocess.run(["git", "ls-files", "-z", *args], check=True, capture_output=True).stdout
    for raw in listed.split(b"\0"):
        path = raw.decode("utf-8", "surrogateescape")
        if path and not os.path.islink(path) and os.path.isfile(path):
            yield path


def is_upstream_pointer(path):
    if os.path.getsize(path) > 1024:
        return False
    with open(path, "rb") as f:
        return f.read(len(POINTER)) == POINTER


def read_lines(path):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", errors="surrogateescape") as f:
        return f.read().splitlines()


def write_lines(path, lines):
    with open(path, "w", encoding="utf-8", errors="surrogateescape") as f:
        f.write("\n".join(lines) + "\n")


def update_gitignore():
    lines = read_lines(".gitignore")
    if BEGIN in lines:
        start, stop = lines.index(BEGIN), lines.index(END)
        kept, lines = lines[start + 1:stop], lines[:start] + lines[stop + 1:]
    else:
        kept = []
    placeholders = {unescape(p) for p in kept}
    placeholders = {p for p in placeholders if os.path.lexists(p)}
    placeholders.update(p for p in git_files("--others", "--exclude-standard") if is_upstream_pointer(p))
    while lines and not lines[-1]:
        lines.pop()
    write_lines(".gitignore", lines + [BEGIN] + [escape(p, " ") for p in sorted(placeholders)] + [END])
    return len(placeholders)


def update_gitattributes():
    suffixes = tuple("." + p for p in PATTERNS)
    large = {unescape(line.split(" ")[0]) for line in read_lines(".gitattributes") if line.startswith("/")}
    large = {p for p in large if os.path.lexists(p)}
    for p in git_files("--cached", "--others", "--exclude-standard"):
        if os.path.getsize(p) >= THRESHOLD and not p.lower().endswith(suffixes):
            large.add(p)
    lines = ["# Generated by tools/lfs_attributes.py - do not edit by hand."]
    lines += [f"*.{p} {LFS}" for p in PATTERNS]
    lines += [f"# Files of {THRESHOLD >> 20} MiB or more that the patterns above do not cover."]
    lines += [f"{escape(p)} {LFS}" for p in sorted(large)]
    write_lines(".gitattributes", lines)
    return len(large)


def main():
    placeholders = update_gitignore()
    large = update_gitattributes()
    print(f"{len(PATTERNS)} LFS patterns, {large} individual LFS files, {placeholders} upstream placeholders ignored")


if __name__ == "__main__":
    main()
